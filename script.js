const originalMarkup = new Map();
const languageButtons = document.querySelectorAll(".language-button");
const menuToggle = document.querySelector(".menu-toggle");
const primaryNav = document.querySelector(".primary-nav");
const toTop = document.querySelector(".to-top");
const originalAria = new Map();
const originalAlt = new Map();
let currentLanguage = document.documentElement.lang === "en" ? "en" : "bn";

document.querySelectorAll("[data-i18n]").forEach((element) => {
  originalMarkup.set(element, element.innerHTML);
});

document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
  originalAria.set(element, element.getAttribute("aria-label"));
});

document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
  originalAlt.set(element, element.alt);
});

function setLanguage(language) {
  const isEnglish = language === "en";
  currentLanguage = language;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.innerHTML = isEnglish && english[key] ? english[key] : originalMarkup.get(element);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.dataset.i18nAria;
    if (element === menuToggle) {
      const open = menuToggle.getAttribute("aria-expanded") === "true";
      element.setAttribute("aria-label", isEnglish
        ? (open ? english.menuClose : english.menuOpen)
        : (open ? "মেনু বন্ধ করুন" : originalAria.get(element)));
    } else {
      element.setAttribute("aria-label", isEnglish ? english[key] : originalAria.get(element));
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (isEnglish && english[key]) element.alt = english[key];
    else element.alt = originalAlt.get(element);
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === language;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  document.title = isEnglish
    ? "Beautiful Bangladesh — A poem written by nature"
    : "সৌন্দর্যের বাংলাদেশ — Beautiful Bangladesh";
  document.querySelector('meta[name="description"]').content = isEnglish
    ? "Discover Bangladesh through its rivers, forests, hills, coast, heritage and welcoming people."
    : "নদী, বন, পাহাড়, সমুদ্র আর মানুষের গল্পে বাংলাদেশকে আবিষ্কার করুন।";
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

menuToggle.addEventListener("click", () => {
  const open = menuToggle.getAttribute("aria-expanded") !== "true";
  menuToggle.setAttribute("aria-expanded", String(open));
  menuToggle.setAttribute("aria-label", open
    ? (currentLanguage === "en" ? english.menuClose : "মেনু বন্ধ করুন")
    : (currentLanguage === "en" ? english.menuOpen : "মেনু খুলুন"));
  primaryNav.classList.toggle("is-open", open);
});

primaryNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.setAttribute("aria-label", currentLanguage === "en" ? english.menuOpen : "মেনু খুলুন");
    primaryNav.classList.remove("is-open");
  });
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && primaryNav.classList.contains("is-open")) {
    menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.setAttribute("aria-label", currentLanguage === "en" ? english.menuOpen : "মেনু খুলুন");
    primaryNav.classList.remove("is-open");
    menuToggle.focus();
  }
});

function updateScrollControls() {
  toTop.classList.toggle("is-visible", window.scrollY > 500);
}

window.addEventListener("scroll", updateScrollControls, { passive: true });
toTop.addEventListener("click", () => window.scrollTo({ top: 0, behavior: "smooth" }));
document.getElementById("year").textContent = new Date().getFullYear();

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries, currentObserver) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        currentObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));
} else {
  document.querySelectorAll(".reveal").forEach((element) => element.classList.add("is-visible"));
}

updateScrollControls();
